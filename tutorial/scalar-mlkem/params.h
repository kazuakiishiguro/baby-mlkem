#ifndef EDU_MLKEM_PARAMS_H
#define EDU_MLKEM_PARAMS_H

/* FIPS 203, ML-KEM-768 parameter set. */
enum {
  EDU_N = 256,
  EDU_Q = 3329,
  EDU_K = 3,
  EDU_ETA1 = 2,
  EDU_ETA2 = 2,
  EDU_DU = 10,
  EDU_DV = 4,

  EDU_POLY12_BYTES = EDU_N * 12 / 8,
  EDU_POLY10_BYTES = EDU_N * EDU_DU / 8,
  EDU_POLY4_BYTES = EDU_N * EDU_DV / 8,

  EDU_PKE_SECRET_KEY_BYTES = EDU_K * EDU_POLY12_BYTES,
  EDU_PUBLIC_KEY_BYTES = EDU_K * EDU_POLY12_BYTES + 32,
  EDU_CIPHERTEXT_BYTES = EDU_K * EDU_POLY10_BYTES + EDU_POLY4_BYTES,
  EDU_SECRET_KEY_BYTES =
      EDU_PKE_SECRET_KEY_BYTES + EDU_PUBLIC_KEY_BYTES + 64,
  EDU_SHARED_SECRET_BYTES = 32,
  EDU_KEYPAIR_COINS_BYTES = 64,
  EDU_ENCAPS_COINS_BYTES = 32
};

#endif
